#!/usr/bin/env python3
"""
clipboard panel — what you copied, in iTerm2's side panel (the toolbelt), in place of iTerm2's
built-in Paste History. That one can't be restyled: every item was one cut-off line of monospace,
four pasted screenshots read as four identical /var/folders/… paths, and a copied key sat there in
plain text.

It watches the Mac's clipboard — anything copied anywhere, not only in iTerm2 — and skips what a
password manager marks private. Pictures show as thumbnails; text that looks like a key or token
stays hidden until you ask. Click an item and it pastes into the tab you're in: bracketed when that
session has bracketed paste on, the way iTerm2's own paste is, and a picture as the path of its saved
copy, the way iTerm2 pastes an image. A picture's thumbnail opens it bigger, and from there in
Preview. The history lives in memory, so a restart clears it; the notes box at the top is a plain
text file (NOTES) and stays.

  uv run --with iterm2 --with pyobjc-framework-Cocoa python panel.py              run it in the foreground
  uv run --with iterm2 --with pyobjc-framework-Cocoa python panel.py --install    start at login (LaunchAgent)
  uv run --with iterm2 --with pyobjc-framework-Cocoa python panel.py --uninstall  stop it and remove the LaunchAgent

The list is your clipboard, so the server answers only on 127.0.0.1, only to its own Host, and only
to requests carrying the key it put in the page it served. Same shape as ../session-panel/panel.py.
"""

import asyncio
import hashlib
import json
import os
import plistlib
import re
import secrets
import shlex
import shutil
import subprocess
import sys
import tempfile
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

HERE = Path(__file__).resolve().parent
HOME = Path.home()
PORT = 47821
HOST = f"127.0.0.1:{PORT}"
TOOL_ID = "com.example.clipboard-panel"
LABEL = "com.example.clipboard-panel"
PLIST = HOME / "Library" / "LaunchAgents" / f"{LABEL}.plist"
LOG = HOME / ".claude" / "logs" / "clipboard-panel.log"
PICTURES = Path(tempfile.gettempdir()) / "clipboard-panel"  # copied pictures, wiped at start
NOTES = HOME / "Library" / "Application Support" / "clipboard-panel" / "notes.txt"
KEY = secrets.token_urlsafe(24)
MAX_ITEMS = 100
PREVIEW_CHARS = 4000  # the page gets this much of an item; paste and copy use all of it
POLL_S = 0.5

# Types a password manager or a generator puts on the clipboard to say "don't keep this"
# (nspasteboard.org's markers, plus 1Password's own).
PRIVATE = {
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
}
# A key or token: one long word mixing upper, lower and digits, or a known key prefix.
KEY_PREFIX = re.compile(r"^(sk[-_]|pk_|rk_|ghp_|gho_|ghs_|github_pat_|glpat-|xox[abprs]-|npm_|AKIA|eyJ)")
ONE_WORD = re.compile(r"[A-Za-z0-9_\-+=/.~:]{24,512}")
ID_ONLY = re.compile(r"[0-9a-fA-F-]+")  # a git sha or a UUID is not a secret


def log(*parts):
    print(time.strftime("%Y-%m-%d %H:%M:%S"), *parts, flush=True)


def looks_secret(text):
    s = text.strip()
    if not ONE_WORD.fullmatch(s) or s.startswith(("/", "~", ".", "http")) or ID_ONLY.fullmatch(s):
        return False
    if KEY_PREFIX.match(s):
        return True
    return bool(re.search(r"\d", s) and re.search(r"[a-z]", s) and re.search(r"[A-Z]", s))


# ---------------------------------------------------------------- LaunchAgent


def install():
    uv = shutil.which("uv") or "/opt/homebrew/bin/uv"
    LOG.parent.mkdir(parents=True, exist_ok=True)
    PLIST.parent.mkdir(parents=True, exist_ok=True)
    PLIST.write_bytes(plistlib.dumps({
        "Label": LABEL,
        "ProgramArguments": [uv, "run", "--quiet", "--with", "iterm2", "--with", "pyobjc-framework-Cocoa", "python", "-I", str(Path(__file__).resolve())],
        "EnvironmentVariables": {"PATH": "/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin", "HOME": str(HOME)},
        "WorkingDirectory": str(HERE),
        "RunAtLoad": True,
        "KeepAlive": True,
        "ThrottleInterval": 15,
        "StandardOutPath": str(LOG),
        "StandardErrorPath": str(LOG),
    }))
    domain = f"gui/{os.getuid()}"
    subprocess.run(["launchctl", "bootout", f"{domain}/{LABEL}"], capture_output=True)
    subprocess.run(["launchctl", "bootstrap", domain, str(PLIST)], check=True)
    print(f"installed {PLIST}; log at {LOG}")


def uninstall():
    subprocess.run(["launchctl", "bootout", f"gui/{os.getuid()}/{LABEL}"], capture_output=True)
    PLIST.unlink(missing_ok=True)
    print("removed the LaunchAgent; the panel goes blank once iTerm2 restarts")


# ---------------------------------------------------------------- the clipboard


class Clips:
    """What was copied, newest first. Copying something already in the list moves it to the top."""

    def __init__(self):
        self.items = []
        self.ver = 0
        self.error = None
        self.lock = threading.Lock()

    def add(self, item):
        with self.lock:
            old = next((i for i in self.items if i["key"] == item["key"]), None)
            if old:
                self.items.remove(old)
                old["at"] = item["at"]
                item = old
            self.items.insert(0, item)
            for gone in self.items[MAX_ITEMS:]:
                self.forget(gone)
            del self.items[MAX_ITEMS:]
            self.ver += 1

    def forget(self, item):
        if item.get("file"):
            Path(item["file"]).unlink(missing_ok=True)

    def remove(self, ids=None):
        """Drops the items with these ids, or every item when no ids are given."""
        with self.lock:
            for item in [i for i in self.items if ids is None or i["id"] in ids]:
                self.items.remove(item)
                self.forget(item)
            self.ver += 1

    def find(self, cid):
        with self.lock:
            return next((i for i in self.items if i["id"] == cid), None)

    def public(self):
        with self.lock:
            return [{
                "id": i["id"], "kind": i["kind"], "at": i["at"], "secret": i.get("secret", False),
                "text": i.get("text", "")[:PREVIEW_CHARS], "chars": len(i.get("text", "")),
                "lines": i.get("text", "").count("\n") + 1, "w": i.get("w"), "h": i.get("h"),
            } for i in self.items]


CLIPS = Clips()


class Notes:
    """The notes box at the top of the panel. Every open panel shows the same notes."""

    def __init__(self):
        self.text = NOTES.read_text() if NOTES.exists() else ""
        self.ver = 1
        self.lock = threading.Lock()

    def save(self, text):
        with self.lock:
            NOTES.parent.mkdir(parents=True, exist_ok=True)
            tmp = NOTES.with_suffix(".tmp")
            tmp.write_text(text)
            tmp.replace(NOTES)
            self.text = text
            self.ver += 1
            return self.ver


NOTES_BOX = Notes()


def read_pasteboard(pb):
    """The clipboard's content as an item, or None when there is nothing to keep."""
    from AppKit import NSBitmapImageRep, NSBitmapImageFileTypePNG, NSPasteboardURLReadingFileURLsOnlyKey, NSURL

    types = set(pb.types() or [])
    if not types or types & PRIVATE:
        return None
    now = time.time()
    if "public.file-url" in types:
        urls = pb.readObjectsForClasses_options_([NSURL], {NSPasteboardURLReadingFileURLsOnlyKey: True}) or []
        paths = [str(u.path()) for u in urls]
        if paths:
            return {"kind": "file", "text": "\n".join(paths), "key": "f:" + "\n".join(paths), "at": now}
    text = pb.stringForType_("public.utf8-plain-text")
    if text is not None:
        text = str(text)
        if not text.strip():
            return None
        return {"kind": "text", "text": text, "secret": looks_secret(text), "key": "t:" + hashlib.sha1(text.encode()).hexdigest(), "at": now}
    data = pb.dataForType_("public.png") or pb.dataForType_("public.tiff")
    if data:
        rep = NSBitmapImageRep.imageRepWithData_(data)
        if rep is None:
            return None
        png = bytes(data) if pb.dataForType_("public.png") else bytes(rep.representationUsingType_properties_(NSBitmapImageFileTypePNG, {}))
        digest = hashlib.sha1(png).hexdigest()
        return {"kind": "image", "png": png, "w": int(rep.pixelsWide()), "h": int(rep.pixelsHigh()), "key": "i:" + digest, "at": now}
    if types & {"public.utf8-plain-text", "public.png", "public.tiff", "public.file-url"}:
        raise PermissionError("macOS gave back nothing for what is on the clipboard — check System Settings › Privacy & Security › Paste from Other Apps")
    return None


def watch():
    """Polls the clipboard's change count — macOS has no change notification — and keeps what changed."""
    from AppKit import NSPasteboard

    pb = NSPasteboard.generalPasteboard()
    seen = None
    while True:
        try:
            count = pb.changeCount()
            if count != seen:
                seen = count
                item = read_pasteboard(pb)
                if item:
                    if item["kind"] == "image":
                        png = item.pop("png")
                        item["file"] = str(PICTURES / f"{item['key'][2:14]}.png")
                        if not Path(item["file"]).exists():
                            Path(item["file"]).write_bytes(png)
                    item["id"] = secrets.token_hex(6)
                    CLIPS.add(item)
                CLIPS.error = None
        except Exception as e:  # noqa: BLE001 — one bad read must not stop the watcher
            if CLIPS.error != str(e)[:300]:
                log("clipboard read failed:", repr(e)[:300])
            CLIPS.error = str(e)[:300]
        time.sleep(POLL_S)


def set_pasteboard(item):
    """Puts an item back on the clipboard, as what it was: a picture, files, or text."""
    from AppKit import NSPasteboard, NSURL
    from Foundation import NSData

    pb = NSPasteboard.generalPasteboard()
    pb.clearContents()
    if item["kind"] == "image":
        png = Path(item["file"]).read_bytes()
        pb.setData_forType_(NSData.dataWithBytes_length_(png, len(png)), "public.png")
    elif item["kind"] == "file":
        pb.writeObjects_([NSURL.fileURLWithPath_(p) for p in item["text"].split("\n")])
    else:
        pb.setString_forType_(item["text"], "public.utf8-plain-text")


def paste_text(item):
    """What a paste of this item types: the text, a picture's saved copy's path, or the files' paths."""
    if item["kind"] == "image":
        return item["file"]
    if item["kind"] == "file":
        return " ".join(shlex.quote(p) for p in item["text"].split("\n"))
    return item["text"]


# ---------------------------------------------------------------- iTerm2


class Panel:
    def __init__(self, connection):
        self.conn = connection
        self.loop = asyncio.get_running_loop()

    async def paste(self, item):
        app = await iterm2.async_get_app(self.conn)
        win = app.current_terminal_window
        sess = win and win.current_tab and win.current_tab.current_session
        if sess is None:
            return {"ok": False, "message": "No terminal tab is open."}
        text = paste_text(item)
        # The menu's tick follows the session in front: on means the program asked for bracketed paste.
        try:
            bracketed = (await iterm2.MainMenu.async_get_menu_item_state(self.conn, "Paste Bracketing")).checked
        except iterm2.mainmenu.MenuItemException:
            bracketed = False
        if bracketed:
            text = "\x1b[200~" + text.replace("\x1b[201~", "") + "\x1b[201~"
        await sess.async_send_text(text)
        await sess.async_activate(select_tab=True, order_window_front=True)
        return {"ok": True}


# ---------------------------------------------------------------- HTTP

PANEL = None
ID_RE = re.compile(r"[0-9a-f]{12}")


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass

    def reply(self, code, body, ctype="application/json"):
        data = body.encode() if isinstance(body, str) else body
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Cache-Control", "no-store")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def query(self):
        return dict(p.split("=", 1) for p in self.path.partition("?")[2].split("&") if "=" in p)

    def ours(self, keyed=True):
        """Our own Host, and — for everything but the page itself — the page's key, as a header
        or (for an <img>, which can't send one) as ?k=."""
        if self.headers.get("Host") != HOST:
            return False
        return not keyed or KEY in (self.headers.get("X-Panel-Key"), self.query().get("k"))

    def do_GET(self):
        path = self.path.split("?")[0]
        if path == "/" and self.ours(keyed=False):
            html = (HERE / "index.html").read_text().replace("__PANEL_KEY__", KEY)
            return self.reply(200, html, "text/html; charset=utf-8")
        if not self.ours():
            return self.reply(403, '{"error":"forbidden"}')
        if path == "/api/clips":
            # The page says which version it has; the items come only when they changed.
            state = {"v": CLIPS.ver, "nv": NOTES_BOX.ver, "error": CLIPS.error, "page": int((HERE / "index.html").stat().st_mtime)}
            if self.query().get("v") != str(CLIPS.ver):
                state["items"] = CLIPS.public()
            if self.query().get("nv") != str(NOTES_BOX.ver):
                state["notes"] = NOTES_BOX.text
            return self.reply(200, json.dumps(state))
        m = re.fullmatch(r"/img/([0-9a-f]{12})", path)
        item = m and CLIPS.find(m.group(1))
        if item and item["kind"] == "image" and Path(item["file"]).exists():
            return self.reply(200, Path(item["file"]).read_bytes(), "image/png")
        self.reply(404, '{"error":"not found"}')

    def do_POST(self):
        if not self.ours() or self.headers.get("X-Panel-Key") != KEY:
            return self.reply(403, '{"error":"forbidden"}')
        try:
            body = json.loads(self.rfile.read(int(self.headers.get("Content-Length") or 0)) or b"{}")
        except ValueError:
            return self.reply(400, '{"error":"bad json"}')
        path = self.path.split("?")[0]
        try:
            if path == "/api/clear":
                CLIPS.remove()
                return self.reply(200, '{"ok":true}')
            if path == "/api/notes":
                text = body.get("text")
                if not isinstance(text, str) or len(text) > 1_000_000:
                    return self.reply(400, '{"ok":false,"message":"Notes must be text under a million characters."}')
                return self.reply(200, json.dumps({"ok": True, "nv": NOTES_BOX.save(text)}))
            cid = str(body.get("id") or "")
            item = ID_RE.fullmatch(cid) and CLIPS.find(cid)
            if not item:
                return self.reply(404, '{"ok":false,"message":"That item is gone from the list."}')
            if path == "/api/paste":
                result = asyncio.run_coroutine_threadsafe(PANEL.paste(item), PANEL.loop).result(30)
            elif path == "/api/copy":
                set_pasteboard(item)
                result = {"ok": True}
            elif path == "/api/remove":
                CLIPS.remove({cid})
                result = {"ok": True}
            elif path == "/api/preview" and item["kind"] == "image":
                done = subprocess.run(["open", "-a", "Preview", item["file"]], capture_output=True, text=True)
                result = {"ok": done.returncode == 0, "message": done.stderr.strip()[:300]}
            else:
                return self.reply(404, '{"error":"not found"}')
            self.reply(200, json.dumps(result))
        except Exception as e:  # noqa: BLE001
            log(path, "failed:", repr(e)[:300])
            self.reply(500, json.dumps({"ok": False, "message": str(e)[:300]}))


async def bind():
    """The port, once a copy started by hand (or one still shutting down) lets go of it."""
    while True:
        try:
            return ThreadingHTTPServer(("127.0.0.1", PORT), Handler)
        except OSError as e:
            if e.errno != 48:  # EADDRINUSE
                raise
            log(f"port {PORT} is held by another copy of the panel; trying again in 10s")
            await asyncio.sleep(10)


async def main(connection):
    global PANEL
    PANEL = Panel(connection)
    server = await bind()
    threading.Thread(target=server.serve_forever, daemon=True).start()
    await iterm2.tool.async_register_web_view_tool(connection, "Clipboard", TOOL_ID, True, f"http://{HOST}/")
    log(f"panel up on http://{HOST}/")
    while True:
        await asyncio.sleep(15)
        try:
            await iterm2.MainMenu.async_get_menu_item_state(connection, "Show Toolbelt")
        except Exception as e:  # noqa: BLE001 — a quit iTerm2 drops the tool; launchd restarts us to register again
            log("iTerm2 connection looks gone; exiting so launchd restarts the panel:", repr(e)[:200])
            os._exit(1)


def iterm_running():
    return subprocess.run(["pgrep", "-x", "iTerm2"], capture_output=True).returncode == 0


if __name__ == "__main__":
    if "--install" in sys.argv:
        install()
    elif "--uninstall" in sys.argv:
        uninstall()
    else:
        import iterm2  # noqa: E402 — only the running panel needs it; --install runs without it

        shutil.rmtree(PICTURES, ignore_errors=True)
        PICTURES.mkdir(mode=0o700, parents=True)
        threading.Thread(target=watch, daemon=True).start()
        while not iterm_running():  # never launch iTerm2 ourselves; wait for the person to open it
            time.sleep(5)
        time.sleep(3)  # let iTerm2's API server come up
        iterm2.run_until_complete(main)
